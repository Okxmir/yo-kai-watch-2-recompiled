[CmdletBinding()]
param([Parameter(Mandatory=$true)][string]$Compiler)
$ErrorActionPreference='Stop'
$root=Split-Path -Parent $PSScriptRoot
$dir=Join-Path $root 'source/clockwork/runtime/src/video/gpu'
$Compiler=(Resolve-Path -LiteralPath $Compiler).Path
$out=Join-Path $root 'build/tools/blit_lcd_post.spv'
$shader=Join-Path $dir 'shaders/blit_lcd_post.frag'
& $Compiler -V --target-env vulkan1.0 -Os $shader -o $out
if($LASTEXITCODE -ne 0){throw 'Optional LCD shader compilation failed.'}
$bytes=[IO.File]::ReadAllBytes($out)
if($bytes.Length -lt 20 -or [BitConverter]::ToUInt32($bytes,0) -ne 0x07230203){throw 'Invalid SPIR-V output.'}
$lines=New-Object 'System.Collections.Generic.List[string]'
$lines.Add('// Generated by scripts/build-lcd-post.ps1 from shaders/blit_lcd_post.frag.')
$lines.Add('static const unsigned char SPIRV_blit_lcd_post_frag[] = {')
for($i=0;$i -lt $bytes.Length;$i+=16){
    $last=[Math]::Min($bytes.Length-1,$i+15)
    $lines.Add('    '+(($bytes[$i..$last] | ForEach-Object {'0x{0:x2},' -f $_}) -join ''))
}
$lines.Add('};')
[IO.File]::WriteAllLines((Join-Path $dir 'lcd_post.inc'),$lines,(New-Object Text.UTF8Encoding($false)))
